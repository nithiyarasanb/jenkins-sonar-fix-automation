import json
import os
import sys
import urllib.error
import urllib.request
from pathlib import Path
from common import RESULTS, ensure_results

def request_json(url, token, payload):
    req = urllib.request.Request(url, data=json.dumps(payload).encode(), headers={
        "Authorization": "Bearer " + token,
        "Content-Type": "application/json",
        "Accept": "application/json"
    }, method="POST")
    try:
        with urllib.request.urlopen(req, timeout=30) as response:
            body = response.read().decode()
            return json.loads(body) if body else {}
    except urllib.error.HTTPError as e:
        raise RuntimeError(f"Bitbucket API error {e.code}: {e.read().decode(errors='replace')[:1000]}")

def main():
    token = os.environ["BITBUCKET_TOKEN"]
    base = os.getenv("BITBUCKET_BASE_URL", "https://api.bitbucket.org/2.0").rstrip("/")
    workspace = os.environ.get("BITBUCKET_WORKSPACE", "")
    repo = os.environ["BITBUCKET_REPO_SLUG"]
    default_branch = os.getenv("BITBUCKET_DEFAULT_BRANCH", "main")
    validated = json.loads((RESULTS / "validation.json").read_text())
    if not validated.get("validated") or not (RESULTS / "validated.patch").exists():
        raise RuntimeError("Patch has not passed validation; refusing to create PR")

    # This script expects Jenkins to have created/pushed the remediation branch
    # in a separate hardened stage. Branch push is intentionally not performed here.
    branch = os.getenv("REMEDIATION_BRANCH", "")
    if not branch.startswith("sonar-remediation/"):
        raise RuntimeError("REMEDIATION_BRANCH must start with sonar-remediation/")
    title = os.getenv("PR_TITLE", "Proposed SonarQube Critical/High remediation")
    body = (
        "## Automated remediation proposal\n\n"
        "This PR was generated by the Jenkins SonarQube remediation workflow.\n\n"
        "### Validation\n"
        f"- Validation command: `{validated.get('validation_command', 'not recorded')}`\n"
        "- Patch application: passed\n"
        "- Human review: **required**\n\n"
        "Please review the diff and test evidence before merging. No merge or deployment was performed by the remediation bot."
    )
    if base == "https://api.bitbucket.org/2.0":
        if not workspace:
            raise RuntimeError("BITBUCKET_WORKSPACE is required for Bitbucket Cloud")
        url = f"{base}/repositories/{workspace}/{repo}/pullrequests"
        payload = {
            "title": title, "description": body, "close_source_branch": False,
            "source": {"branch": {"name": branch}},
            "destination": {"branch": {"name": default_branch}},
            "reviewers": []
        }
    else:
        raise RuntimeError("Bitbucket Data Center PR adapter is not implemented in this starter; add and test your version-specific REST endpoint.")
    result = request_json(url, token, payload)
    link = result.get("links", {}).get("html", {}).get("href", "")
    (RESULTS / "pull-request.json").write_text(json.dumps({"id": result.get("id"), "url": link, "branch": branch}, indent=2))
    print("Pull Request created:", link or result.get("id"))
if __name__ == "__main__":
    try: main()
    except Exception as e:
        print(f"ERROR: {e}", file=sys.stderr); sys.exit(1)
